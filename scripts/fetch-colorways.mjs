// Vendors full-size colorway images for every recommendations shelf in the
// capture and generates src/lib/nordstrom/colorways.ts.
//
// Swatch chips in the capture are tiny CDN crops of the same image id the
// product photo uses (…/it/<uuid>.jpeg?h=28…). Hovering a chip should show
// the product in that colour, so for every chip url in the capture (Top
// Picks, Great Deals, and Trending Near You all use the same chip markup)
// we download …/it/<uuid>.jpeg?w=600&quality=85 and map the chip's local
// file name (sha1 of the chip url, same scheme as fetch-media.mjs) to the
// local full-size file.
// Run: node scripts/fetch-colorways.mjs
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const CAPTURE = "scripts/nordstrom-capture.html";
const OUT_DIR = "public/assets/media";
const OUT_TS = "src/lib/nordstrom/colorways.ts";
const FULL_PARAMS = "w=600&quality=85";

function sha1(s) {
  return crypto.createHash("sha1").update(s).digest("hex").slice(0, 20);
}

const html = fs.readFileSync(CAPTURE, "utf8");

const chips = [];
for (const m of html.matchAll(
  /aria-label="([^"]*)"[^>]*style="background-image: url\(&quot;(https:\/\/n\.nordstrommedia\.com\/[^&]+(?:&amp;[^&"]*)*)&quot;\);"/g,
)) {
  const name = m[1];
  const raw = m[2].split("&quot;")[0];
  if (/\.pdf(\?|$)/.test(raw)) continue;
  chips.push({ name, raw });
}
console.log("swatch chips:", chips.length);

const seen = new Set();
const todo = [];
const manifest = {};
for (const { raw } of chips) {
  const chipFile = `${sha1(raw)}${path.extname(raw.split("?")[0])}`;
  if (seen.has(chipFile)) continue;
  seen.add(chipFile);
  const pathOnly = raw.split("?")[0];
  const fullUrl = `${pathOnly}?${FULL_PARAMS}`;
  const fullFile = `${sha1(fullUrl)}.jpeg`;
  manifest[chipFile] = `/assets/media/${fullFile}`;
  if (!fs.existsSync(path.join(OUT_DIR, fullFile))) todo.push({ fullUrl, fullFile });
}

console.log("unique colorways:", seen.size, "| to download:", todo.length);
fs.mkdirSync(OUT_DIR, { recursive: true });

async function grab({ fullUrl, fullFile }) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(fullUrl, { signal: AbortSignal.timeout(30000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      fs.writeFileSync(path.join(OUT_DIR, fullFile), Buffer.from(await res.arrayBuffer()));
      return null;
    } catch (err) {
      if (attempt === 3) return `${fullUrl} -> ${err.message}`;
      await new Promise((r) => setTimeout(r, attempt * 1000));
    }
  }
}

const queue = [...todo];
const failures = [];
await Promise.all(
  Array.from({ length: 6 }, async () => {
    for (let job = queue.shift(); job; job = queue.shift()) {
      const err = await grab(job);
      if (err) failures.push(err);
    }
  }),
);
console.log("downloaded:", todo.length - failures.length, "failed:", failures.length);
for (const f of failures) console.log("  FAIL", f);

const ts =
  "// Generated by scripts/fetch-colorways.mjs from the vendored capture.\n" +
  "// Maps a swatch-chip file name (public/assets/media/<sha1 of chip url>)\n" +
  "// to the vendored full-size colorway image used on hover / in Quick View.\n" +
  "export const COLORWAY_IMAGES: Record<string, string> = " +
  JSON.stringify(manifest, null, 2) +
  ";\n";
fs.writeFileSync(OUT_TS, ts);
console.log("wrote", OUT_TS, Object.keys(manifest).length, "entries");
process.exit(failures.length ? 1 : 0);
